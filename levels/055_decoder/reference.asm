section .text
ring_insn_length:               ; rdi = code
    mov rsi, rdi                ; p
    xor r8d, r8d                ; bit 0: 66 seen, bit 1: REX.W
    lea r9, [rel one_byte]
.prefix:
    movzx eax, byte [rsi]
    test byte [r9 + rax], PFX
    jz .rex
    cmp al, 0x66
    jne .next_prefix
    or r8d, 1
.next_prefix:
    inc rsi
    jmp .prefix
.rex:
    mov ecx, eax
    and ecx, 0xF0
    cmp ecx, 0x40
    jne .opcode
    test al, 8
    jz .rex_done
    or r8d, 2                   ; REX.W
.rex_done:
    inc rsi
    movzx eax, byte [rsi]
.opcode:
    inc rsi
    cmp al, 0x0F
    je .two
    movzx edx, byte [r9 + rax]  ; the flags
    mov r10d, eax               ; the opcode, for F6 and E8/E9
    jmp .modrm
.two:
    movzx eax, byte [rsi]
    inc rsi
    lea r9, [rel two_byte]
    movzx edx, byte [r9 + rax]
    mov r10d, 0x100
    cmp al, 0x38
    je .third
    cmp al, 0x3A
    jne .modrm
.third:
    inc rsi                     ; 0F 38 xx / 0F 3A xx
.modrm:
    test edx, M
    jz .immediates
    movzx eax, byte [rsi]       ; ModRM
    inc rsi
    mov ecx, eax
    shr ecx, 6                  ; mod
    cmp ecx, 3
    je .group3
    mov r11d, eax
    and r11d, 7                 ; r/m
    cmp r11d, 4
    jne .no_sib
    movzx r11d, byte [rsi]      ; SIB
    inc rsi
    and r11d, 7                 ; base
    test ecx, ecx
    jnz .disp
    cmp r11d, 5                 ; mod 0, base 5: disp32, no base
    jne .group3
    add rsi, 4
    jmp .group3
.no_sib:
    test ecx, ecx
    jnz .disp
    cmp r11d, 5                 ; mod 0, r/m 5: [rip + disp32]
    jne .group3
    add rsi, 4
    jmp .group3
.disp:
    cmp ecx, 1
    jne .disp32
    inc rsi                     ; disp8
    jmp .group3
.disp32:
    add rsi, 4
.group3:
    test edx, GRP3
    jz .immediates
    shr eax, 3
    and eax, 7                  ; the reg field
    cmp eax, 1
    ja .immediates              ; only test (/0, /1) has an immediate
    cmp r10d, 0xF6
    je .imm8
    jmp .immz
.immediates:
    test edx, I8
    jnz .imm8
    test edx, IZ
    jnz .immz
    test edx, I16
    jnz .imm16
    test edx, MOVI
    jz .done
    test r8d, 2
    jnz .imm64
    test r8d, 1
    jnz .imm16
    jmp .imm32
.imm64:
    add rsi, 8
    jmp .done
.imm8:
    inc rsi
    jmp .done
.immz:
    test r8d, 2
    jnz .imm32
    test r8d, 1
    jz .imm32
    cmp r10d, 0xE8              ; call/jmp rel32 ignore 66
    je .imm32
    cmp r10d, 0xE9
    je .imm32
.imm16:
    add rsi, 2
    jmp .done
.imm32:
    add rsi, 4
.done:
    mov rax, rsi
    sub rax, rdi
    ret
